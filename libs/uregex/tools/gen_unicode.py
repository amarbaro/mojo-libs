"""Generate src/uregex/unicode_tables.mojo from the Python `regex` module.

Every class the engine knows (\\p{Xx}, \\d, \\w, \\s) is derived by asking the
oracle itself which codepoints it matches, so engine == oracle by construction;
the differential test in tools/difftest.py then only has to check the matcher.
Case maps come from str.lower()/str.upper() (single-codepoint results only),
stored as fixed-width hex pairs (6+6 chars, sorted) so they are searched in place.
"""
import sys
import unicodedata
from pathlib import Path

import regex

OUT = Path(__file__).resolve().parent.parent / "src/uregex/unicode_tables.mojo"
MAXCP = 0x10FFFF
ALL = "".join(chr(c) for c in range(MAXCP + 1) if not 0xD800 <= c <= 0xDFFF)
CATS = ["L", "Lu", "Ll", "Lt", "Lm", "Lo", "M", "Mn", "Mc", "Me", "N", "Nd", "Nl", "No",
        "P", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "S", "Sm", "Sc", "Sk", "So",
        "Z", "Zs", "Zl", "Zp", "C", "Cc", "Cf", "Co", "Cn"]


def ranges(chars):
    cps = sorted(ord(c) for c in chars)
    out, lo, prev = [], None, None
    for c in cps:
        if lo is None:
            lo = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((lo, prev)); lo = prev = c
    if lo is not None:
        out.append((lo, prev))
    return out


def hexranges(rs):
    return ";".join(f"{a:x}-{b:x}" for a, b in rs)


def matched(pat):
    return regex.findall(pat, ALL)


lines = [
    "# Copyright 2026 amarbaro.org. Licensed under the Apache License, Version 2.0.",
    "# GENERATED by tools/gen_unicode.py -- do not edit.",
    f"# oracle: python regex {regex.__version__}, unicodedata {unicodedata.unidata_version}",
    "",
]
names = []
for cat in CATS:
    rs = ranges(matched(rf"\p{{{cat}}}"))
    names.append(cat)
    lines.append(f'comptime _CAT_{cat} = "{hexranges(rs)}"')
for esc, pat in (("d", r"\d"), ("w", r"\w"), ("s", r"\s")):
    rs = ranges(matched(pat))
    lines.append(f'comptime _ESC_{esc} = "{hexranges(rs)}"')

lower = [(c, ord(chr(c).lower())) for c in range(MAXCP + 1)
         if not 0xD800 <= c <= 0xDFFF and len(chr(c).lower()) == 1 and chr(c).lower() != chr(c)]
upper = [(c, ord(chr(c).upper())) for c in range(MAXCP + 1)
         if not 0xD800 <= c <= 0xDFFF and len(chr(c).upper()) == 1 and chr(c).upper() != chr(c)]
lines.append('comptime _LOWER = "' + "".join(f"{a:06x}{b:06x}" for a, b in lower) + '"')
lines.append('comptime _UPPER = "' + "".join(f"{a:06x}{b:06x}" for a, b in upper) + '"')
lines += ["", "", "def category_table(name: String) -> StaticString:"]
for cat in CATS:
    lines.append(f'    if name == "{cat}":')
    lines.append(f"        return _CAT_{cat}")
lines.append('    return ""')
lines += ["", "", "def escape_table(c: String) -> StaticString:",
          '    if c == "d":', "        return _ESC_d",
          '    if c == "w":', "        return _ESC_w",
          '    if c == "s":', "        return _ESC_s",
          '    return ""',
          "", "", "def lower_table() -> StaticString:", "    return _LOWER",
          "", "", "def upper_table() -> StaticString:", "    return _UPPER", ""]
OUT.write_text("\n".join(lines))
print(OUT, OUT.stat().st_size, "bytes;", len(lower), "lower pairs", len(upper), "upper pairs")
